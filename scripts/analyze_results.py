"""
Analyze how KG grounding changes OpenAI benchmark accuracy.

Input:
    reports/final/results_with_kg.csv

The input is generated by ``src/kg_runner.py``. Each row represents one
benchmark question and contains the vanilla OpenAI answer, the KG-grounded
OpenAI answer, their evaluator-produced correctness labels, and metadata about
the KG reasoning path.

The script prints three diagnostic views:
    1. Regressions: vanilla was correct, but KG-grounded became incorrect.
    2. Improvements: vanilla was incorrect, but KG-grounded became correct.
    3. Accuracy grouped by classified question type.

This is a read-only analysis script. It does not call an LLM, rerun retrieval,
or modify the benchmark report.
"""
import pandas as pd


# Load the final KG comparison report. Correctness columns may be empty when a
# corresponding vanilla or KG answer was unavailable, so comparisons below
# explicitly exclude rows with missing labels.
df = pd.read_csv("reports/final/results_with_kg.csv")

# ---------------------------------------------------------------------------
# Regressions
# ---------------------------------------------------------------------------
# A regression identifies evidence/reasoning that harmed an answer which the
# vanilla model originally answered correctly. These rows are the highest-value
# starting points for debugging incorrect KG facts, retrieval, or prompt use.
print("=" * 80)
print("OPENAI PERFORMANCE DEGRADATION")
print("=" * 80)

for _, row in df.iterrows():
    # Both labels are required to establish a true before-versus-after change.
    if not pd.isna(row["openai_vanilla_is_correct"]) and not pd.isna(
        row["openai_kg_is_correct"]
    ):
        vanilla = bool(row["openai_vanilla_is_correct"])
        kg = bool(row["openai_kg_is_correct"])

        if vanilla and not kg:
            print(f"\nQ{row['id']} - REGRESSED (was correct, now wrong)")
            print(f"  Question: {row['question'][:70]}...")
            # Classification and KG metadata help identify which reasoning path
            # supplied the harmful context without printing the full CSV row.
            print(f"  Primary Type: {row['primary_type']}")
            print(f"  Time Semantic: {row['time_semantic']}")
            print(f"  KG Found: {row['kg_found']} ({int(row['kg_facts_count'])} facts)")
            print(f"  Vanilla Answer: {str(row['openai_vanilla_answer'])[:80]}")
            print(f"  KG Answer: {str(row['openai_kg_answer'])[:80]}")
            print(f"  Ground Truth: {str(row['ground_truth'])[:80]}")

# ---------------------------------------------------------------------------
# Improvements
# ---------------------------------------------------------------------------
# An improvement shows where KG evidence/reasoning corrected an answer that the
# vanilla model missed. The reasoning strategy is printed so successful
# strategies can be inspected and generalized.
print("\n" + "=" * 80)
print("OPENAI PERFORMANCE IMPROVEMENTS")
print("=" * 80)

for _, row in df.iterrows():
    if not pd.isna(row["openai_vanilla_is_correct"]) and not pd.isna(
        row["openai_kg_is_correct"]
    ):
        vanilla = bool(row["openai_vanilla_is_correct"])
        kg = bool(row["openai_kg_is_correct"])

        if not vanilla and kg:
            print(f"\nQ{row['id']} - IMPROVED (was wrong, now correct)")
            print(f"  Question: {row['question'][:70]}...")
            print(f"  Primary Type: {row['primary_type']}")
            print(f"  Time Semantic: {row['time_semantic']}")
            print(f"  Reasoning Strategy: {row['reasoning_strategy']}")
            print(f"  KG Found: {row['kg_found']} ({int(row['kg_facts_count'])} facts)")
            print(f"  Vanilla Answer: {str(row['openai_vanilla_answer'])[:80]}")
            print(f"  KG Answer: {str(row['openai_kg_answer'])[:80]}")

# ---------------------------------------------------------------------------
# Accuracy by question type
# ---------------------------------------------------------------------------
# ``primary_type`` is assigned by QuestionClassifier during the KG benchmark.
# Grouping by it shows whether KG grounding helps some reasoning shapes, such
# as counts or comparisons, while hurting others.
print("\n" + "=" * 80)
print("SUMMARY STATS BY QUESTION TYPE")
print("=" * 80)

for qtype in df["primary_type"].unique():
    subset = df[df["primary_type"] == qtype]

    # Equality with True intentionally excludes missing correctness labels from
    # the numerator. The denominator remains every benchmark row of this type,
    # matching the benchmark's overall accuracy convention.
    vanilla_correct = (subset["openai_vanilla_is_correct"] == True).sum()
    kg_correct = (subset["openai_kg_is_correct"] == True).sum()
    count = len(subset)

    # The guard keeps this calculation safe if the grouping logic is changed
    # later to include an explicitly empty category.
    vanilla_pct = (vanilla_correct / count) * 100 if count > 0 else 0
    kg_pct = (kg_correct / count) * 100 if count > 0 else 0

    print(f"\n{qtype:15} ({count} questions)")
    print(f"  Vanilla: {vanilla_correct}/{count} ({vanilla_pct:.1f}%)")
    print(f"  KG:      {kg_correct}/{count} ({kg_pct:.1f}%)")
    print(f"  Change:  {kg_pct - vanilla_pct:+.1f}%")
